#!/usr/bin/env node
/**
 * Reads assets/art/ and writes src/art/manifest.ts, so each picture is bundled with a static
 * require (Metro needs that). Run after adding, renaming or removing artwork:
 *
 *   npm run art
 */
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';

const DIR = 'assets/art';
const SLOTS_FILE = 'src/art/slots.ts';
const EXT = ['png', 'jpg', 'jpeg', 'webp'];

const slotSource = (await import('node:fs')).readFileSync(SLOTS_FILE, 'utf8');
const slots = [...slotSource.matchAll(/^\s*'?([a-z][a-z-]*)'?:\s*\{\s*size:/gm)].map((m) => m[1]);

const files = existsSync(DIR) ? readdirSync(DIR) : [];
const found = {};
const problems = [];
for (const file of files.sort()) {
  const m = file.match(/^(.+)\.([a-z]+)$/i);
  if (!m) continue;
  const [, name, ext] = m;
  if (!EXT.includes(ext.toLowerCase())) continue;
  if (!slots.includes(name)) {
    problems.push(`"${file}" is not a known slot name (ignored). Slots: ${slots.join(', ')}`);
    continue;
  }
  if (found[name]) {
    problems.push(`"${file}": a picture for "${name}" already exists (${found[name]}) — keep only one.`);
    continue;
  }
  if (statSync(`${DIR}/${file}`).size > 2_500_000) {
    problems.push(`"${file}" is over 2.5 MB — please compress it (the app downloads it).`);
  }
  found[name] = file;
}

const lines = Object.entries(found).map(([slot, file]) => `  '${slot}': require('../../${DIR}/${file}'),`);
writeFileSync(
  'src/art/manifest.ts',
  `// GENERATED by \`npm run art\` — do not edit by hand. Lists the pictures found in assets/art/.
import type { ImageSourcePropType } from 'react-native';

import type { ArtSlot } from './slots';

export const ART_MANIFEST: Partial<Record<ArtSlot, ImageSourcePropType>> = {${lines.length ? `\n${lines.join('\n')}\n` : ''}};
`,
);

console.log(`${Object.keys(found).length} of ${slots.length} pictures in place.`);
const missing = slots.filter((s) => !found[s]);
if (missing.length) console.log(`Still using the built-in drawing: ${missing.join(', ')}`);
for (const p of problems) console.warn(`! ${p}`);
